//go:build !js

package download

import (
	"fmt"
	"github.com/Suhaibinator/Next.go/httpx"
	"net/http"
)

var methods = func() http.Handler {
	handler, err := httpx.Methods(map[string]http.Handler{"GET": http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "text/plain; charset=utf-8")
		_, _ = fmt.Fprintf(w, "Generated by a Go route handler. Name: %s\n", r.PathValue("name"))
	})})
	if err != nil {
		panic(err)
	}
	return handler
}()

// Handle is discovered outside /api too. It receives standard PathValue params
// and bypasses layouts, HTML envelopes, prefetch and client link interception.
func Handle(w http.ResponseWriter, r *http.Request) { methods.ServeHTTP(w, r) }
