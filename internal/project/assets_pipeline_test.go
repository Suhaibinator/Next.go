func TestAssetPipelineOptionalAndInvalid(t *testing.T) {
	root, build := t.TempDir(), t.TempDir()
	result, err := stageAssetPipeline(context.Background(), root, build, nil)
	if err != nil || result != nil {
		t.Fatal(result, err)
	}
	if generatedAssetIdentity(result) != "" {
		t.Fatal("optional pipeline changes identity")
	}
	if err := mergeGeneratedAssets(context.Background(), nil, filepath.Join(build, "missing")); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "nextgo.assets.json"), []byte(`{"version":2,"tools":[]}`), 0644); err != nil {
		t.Fatal(err)
	}
	if _, err := stageAssetPipeline(context.Background(), root, build, nil); err == nil {
		t.Fatal("invalid pipeline did not fail build stage")
	}
}

func TestAssetPipelineSourceWatcherRecovery(t *testing.T) {
	t.Setenv("GOWORK", "off")
	root := t.TempDir()
	writeInput(t, root, "go.mod", "module pipeline.test\ngo 1.24.0\n")
	writeInput(t, root, "app/page.go", "package app\n")
	writeInput(t, root, "styles/main.css", "body{color:blue}")
	var watcher SourceWatcher
	value := func() string {
		t.Helper()
		fingerprint, err := watcher.Fingerprint(context.Background(), root)
		if err != nil {
			t.Fatal(err)
		}
		return fingerprint
	}
	before := value()
	manifest := `{"version":1,"tools":[{"name":"fixture","command":["tool-that-is-never-executed"],"inputs":["styles/main.css"],"outputs":["style.css"]}]}`
	writeInput(t, root, assetPipelineManifest, manifest)
	previous := value()
	if previous == before {
		t.Fatal("manifest addition was not watched")
	}
	assertChanged := func() {
		t.Helper()
		next := value()
		if next == previous {
			t.Fatal("asset input change was not watched")
		}
		previous = next
	}
	writeInput(t, root, "styles/main.css", "body{color:cyan}")
	assertChanged()
	if err := os.Remove(filepath.Join(root, "styles/main.css")); err != nil {
		t.Fatal(err)
	}
	assertChanged()
	if _, err := stageAssetPipeline(context.Background(), root, t.TempDir(), nil); err == nil || !strings.Contains(err.Error(), "inputs") {
		t.Fatal("missing asset input did not fail before tool launch", err)
	}
	writeInput(t, root, "styles/main.css", "body{color:gold}")
	assertChanged()
	writeInput(t, root, assetPipelineManifest, `{"version":invalid-one`)
	assertChanged()
	if _, err := stageAssetPipeline(context.Background(), root, t.TempDir(), nil); err == nil {
		t.Fatal("invalid manifest accepted")
	}
	writeInput(t, root, assetPipelineManifest, `{"version":invalid-two`)
	assertChanged()
	writeInput(t, root, assetPipelineManifest, manifest)
	assertChanged()
	if err := os.Remove(filepath.Join(root, assetPipelineManifest)); err != nil {
		t.Fatal(err)
	}
	assertChanged()
	writeInput(t, root, "styles/main.css", "body{color:pink}")
	if value() != previous {
		t.Fatal("undeclared CSS unexpectedly watched without manifest")
	}
}

func TestGeneratedAssetsNondeterminismChangesBuildIdentity(t *testing.T) {
	root := t.TempDir()
	generation := 0
	pipeline := buildassets.Pipeline{Version: 1, Tools: []buildassets.Tool{{Name: "nondeterministic fixture", Outputs: []string{"style.css"}, Transform: func(_ context.Context, w buildassets.Workspace) error {
		generation++
		return os.WriteFile(filepath.Join(w.Outputs, "style.css"), []byte(strings.Repeat("x", generation)), 0644)
	}}}}
	stage := func(name string) *buildassets.Result {
		t.Helper()
		result, err := buildassets.Run(context.Background(), pipeline, buildassets.Options{Root: root, Stage: filepath.Join(root, name)})
		if err != nil {
			t.Fatal(err)
		}
		return result
	}
	one, two := stage("one"), stage("two")
	buildID := func(result *buildassets.Result) string {
		return runtimeBuildID([]byte("identical wasm"), "identical source"+generatedAssetIdentity(result), []byte("support"), "loader")
	}
	if buildID(one) == buildID(two) {
		t.Fatal("nondeterministic generated bytes reused runtime build identity")
	}
	public := filepath.Join(root, "public")
	writeInput(t, public, "style.css", "existing")
	if err := mergeGeneratedAssets(context.Background(), two, public); err == nil {
		t.Fatal("generated output overwrote existing public file")
	}
	data, err := os.ReadFile(filepath.Join(public, "style.css"))
	if err != nil || string(data) != "existing" {
		t.Fatal("public collision mutated previous data", string(data), err)
	}
}

func TestAssetPipelineGoExampleHook(t *testing.T) {
	root, err := filepath.Abs(filepath.Join("..", "..", "examples", "css-pipeline"))
	if err != nil {
		t.Fatal(err)
	}
	result, err := stageAssetPipeline(context.Background(), root, t.TempDir(), os.Stderr)
	if err != nil {
		t.Fatal(err)
	}
	css, err := os.ReadFile(filepath.Join(result.Dir, "style.css"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(css), "--accent: #c7512b") || strings.Contains(string(css), "{{") {
		t.Fatal("design token transform failed", string(css))
	}
	if _, err := os.Stat(filepath.Join(root, "public", "style.css")); !os.IsNotExist(err) {
		t.Fatal("example generated CSS inside source public", err)
	}
}

func TestEmptyAssetPipelineStagesInBuildGeneration(t *testing.T) {
	root, build := t.TempDir(), t.TempDir()
	if err := os.WriteFile(filepath.Join(root, "nextgo.assets.json"), []byte(`{"version":1,"tools":[]}`), 0644); err != nil {
		t.Fatal(err)
	}
	result, err := stageAssetPipeline(context.Background(), root, build, nil)
	if err != nil {
		t.Fatal(err)
	}
	if filepath.Dir(filepath.Dir(result.Dir)) != build || generatedAssetIdentity(result) == "" {
		t.Fatal(result)
	}
	if _, err := os.Stat(filepath.Join(root, "public")); !os.IsNotExist(err) {
		t.Fatal("pipeline wrote source public")
	}
	public := filepath.Join(build, "server", "assets", "public")
	if err := os.MkdirAll(public, 0755); err != nil {
		t.Fatal(err)
	}
	if err := mergeGeneratedAssets(context.Background(), result, public); err != nil {
		t.Fatal(err)
	}
}
