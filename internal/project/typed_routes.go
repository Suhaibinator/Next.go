const generatedRoutesHeader = "// Code generated by nextgo. DO NOT EDIT.\n"

type typedParameter struct {
	key, field string
	catchall   bool
}
type typedRoute struct {
	pattern, name string
	parameters    []typedParameter
	api           bool
}

func routesFile(root string) string { return filepath.Join(root, "routes", "nextgo_gen.go") }

// TypedRoutesSource emits a portable routes package without importing pages,
// loaders, layouts or application configuration into the browser graph.
func TypedRoutesSource(p *Project) ([]byte, error) {
	routes, err := typedRoutes(p)
	if err != nil {
		return nil, err
	}
	var source strings.Builder
	source.WriteString(generatedRoutesHeader + "\n// Package routes provides application paths and decoded route parameter types.\npackage routes\n")
	for _, route := range routes {
		if len(route.parameters) > 0 {
			fmt.Fprintf(&source, "import routeinfo %q\n", framework+"/routeinfo")
			break
		}
	}
	for _, route := range routes {
		kind := "page"
		if route.api {
			kind = "HTTP endpoint"
		}
		fmt.Fprintf(&source, "\n// %s constructs the application path for %s %s.\n", route.name, kind, route.pattern)
		if len(route.parameters) == 0 {
			// Build escapes static segments too, without adding a runtime import.
			path, err := routing.Build(route.pattern, nil)
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&source, "func %s() string {return %q}\n", route.name, path)
			continue
		}
		fmt.Fprintf(&source, "func %s(p %sParams) (string,error) {return routeinfo.BuildPath(%q,map[string][]string{", route.name, route.name, route.pattern)
		for _, param := range route.parameters {
			if param.catchall {
				fmt.Fprintf(&source, "%q:p.%s,", param.key, param.field)
			} else {
				fmt.Fprintf(&source, "%q:{p.%s},", param.key, param.field)
			}
		}
		source.WriteString("})}\n")
		fmt.Fprintf(&source, "\n// %sParams contains decoded values for %s.\ntype %sParams struct {\n", route.name, route.pattern, route.name)
		for _, param := range route.parameters {
			kind := "string"
			if param.catchall {
				kind = "[]string"
			}
			fmt.Fprintf(&source, "// %s is the decoded %q parameter.\n%s %s\n", param.field, param.key, param.field, kind)
		}
		source.WriteString("}\n")
		fmt.Fprintf(&source, "\n// Read%s validates and copies parameters from Context.Params.\nfunc Read%s(values map[string]string) (%sParams,error) {p:=%sParams{", route.name, route.name, route.name, route.name)
		for _, param := range route.parameters {
			if param.catchall {
				fmt.Fprintf(&source, "%s:routeinfo.SplitParam(values[%q]),", param.field, param.key)
			} else {
				fmt.Fprintf(&source, "%s:values[%q],", param.field, param.key)
			}
		}
		fmt.Fprintf(&source, "};if _,err:=%s(p);err!=nil{return %sParams{},err};return p,nil}\n", route.name, route.name)
	}
	return format.Source([]byte(source.String()))
}

func typedRoutes(p *Project) ([]typedRoute, error) {
	byPattern := map[string]typedRoute{}
	for _, r := range projectRoutes(p.Routes) {
		// Synthetic carriers/defaults describe rendering, not additional URLs.
		if r.Default || r.Missing || r.Pattern == "" {
			continue
		}
		if old, ok := byPattern[r.Pattern]; ok {
			if old.api != r.API {
				return nil, fmt.Errorf("typed routes: mixed page/endpoint for %q", r.Pattern)
			}
			continue
		}
		if _, err := routing.Validate(r.Pattern); err != nil {
			return nil, err
		}
		value := typedRoute{pattern: r.Pattern, api: r.API}
		parts := strings.Split(strings.Trim(r.Pattern, "/"), "/")
		for _, part := range parts {
			if part == "" {
				continue
			}
			if part[0] == ':' || part[0] == '*' {
				key := strings.TrimSuffix(part[1:], "?")
				field := routeIdentifier(key)
				value.name += "By" + field
				value.parameters = append(value.parameters, typedParameter{key: key, field: field, catchall: part[0] == '*'})
			} else {
				value.name += routeIdentifier(part)
			}
		}
		if value.name == "" {
			value.name = "Index"
		}
		// Normalization can merge case/underscore spellings. Keep every field
		// addressable without rejecting an otherwise valid route pattern.
		counts := map[string]int{}
		for _, param := range value.parameters {
			counts[param.field]++
		}
		for i := range value.parameters {
			if counts[value.parameters[i].field] > 1 {
				value.parameters[i].field += fmt.Sprintf("_%d", i+1)
			}
		}
		byPattern[r.Pattern] = value
	}
	routes := make([]typedRoute, 0, len(byPattern))
	for _, r := range byPattern {
		routes = append(routes, r)
	}
	sort.Slice(routes, func(i, j int) bool { return routes[i].pattern < routes[j].pattern })
	// Consider the entire package namespace, including readers and Params types.
	owners := map[string][]int{}
	for i, r := range routes {
		for _, symbol := range typedSymbols(r) {
			owners[symbol] = append(owners[symbol], i)
		}
	}
	collisions := map[int]bool{}
	for _, indexes := range owners {
		if len(indexes) > 1 {
			for _, i := range indexes {
				collisions[i] = true
			}
		}
	}
	for i := range routes {
		if collisions[i] {
			sum := sha256.Sum256([]byte(routes[i].pattern))
			routes[i].name += fmt.Sprintf("_%x", sum[:8])
		}
	}
	seen := map[string]string{}
	for _, r := range routes {
		for _, symbol := range typedSymbols(r) {
			if old, ok := seen[symbol]; ok {
				return nil, fmt.Errorf("typed route symbol collision %q between %q and %q", symbol, old, r.pattern)
			}
			seen[symbol] = r.pattern
		}
	}
	return routes, nil
}

func typedSymbols(r typedRoute) []string {
	if len(r.parameters) == 0 {
		return []string{r.name}
	}
	return []string{r.name, r.name + "Params", "Read" + r.name}
}

func routeIdentifier(value string) string {
	var b strings.Builder
	upper := true
	for _, r := range value {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' {
			if b.Len() == 0 && r >= '0' && r <= '9' {
				b.WriteString("N")
			}
			if upper && r >= 'a' && r <= 'z' {
				r -= 32
			}
			b.WriteRune(r)
			upper = false
		} else {
			upper = true
		}
	}
	if b.Len() == 0 {
		return "Value"
	}
	return b.String()
}

// GenerateRoutes atomically refreshes its owned source file. Check mode never
// writes and reports missing/stale output for CI and editor setup.
func GenerateRoutes(p *Project, check bool) (string, error) {
	data, err := TypedRoutesSource(p)
	if err != nil {
		return "", err
	}
	path := routesFile(p.Root)
	dir := filepath.Dir(path)
	info, err := os.Lstat(dir)
	if err == nil && (!info.IsDir() || info.Mode()&os.ModeSymlink != 0) {
		return "", fmt.Errorf("typed routes directory must be a real directory: %s", dir)
	}
	if err != nil && !os.IsNotExist(err) {
		return "", err
	}
	if err == nil {
		entries, err := os.ReadDir(dir)
		if err != nil {
			return "", err
		}
		for _, entry := range entries {
			if entry.Name() == "go.mod" {
				return "", fmt.Errorf("typed routes cannot use a nested module: %s", dir)
			}
			if entry.Name() == filepath.Base(path) || !strings.HasSuffix(entry.Name(), ".go") {
				continue
			}
			file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, entry.Name()), nil, parser.PackageClauseOnly)
			if err != nil {
				return "", err
			}
			if file.Name.Name != "routes" && !(strings.HasSuffix(entry.Name(), "_test.go") && file.Name.Name == "routes_test") {
				return "", fmt.Errorf("typed routes directory contains package %s; expected routes: %s", file.Name.Name, dir)
			}
		}
	}
	old, err := os.Lstat(path)
	if err == nil {
		if !old.Mode().IsRegular() {
			return "", fmt.Errorf("typed routes output must be a regular file: %s", path)
		}
		existing, err := os.ReadFile(path)
		if err != nil {
			return "", err
		}
		if !bytes.HasPrefix(existing, []byte(generatedRoutesHeader)) {
			return "", fmt.Errorf("refusing to overwrite unowned typed routes file: %s", path)
		}
		if bytes.Equal(existing, data) {
			return path, nil
		}
	} else if !os.IsNotExist(err) {
		return "", err
	}
	if check {
		return "", fmt.Errorf("typed routes missing or stale; run nextgo generate %s", p.Root)
	}
	if err := os.MkdirAll(dir, 0755); err != nil {
		return "", err
	}
	temp, err := os.CreateTemp(dir, ".nextgo-routes-*")
	if err != nil {
		return "", err
	}
	defer os.Remove(temp.Name())
	defer temp.Close()
	if _, err = temp.Write(data); err != nil {
		return "", err
	}
	if err = temp.Chmod(0644); err != nil {
		return "", err
	}
	if err = temp.Close(); err != nil {
		return "", err
	}
	if err = os.Rename(temp.Name(), path); err != nil {
		return "", err
	}
	return path, nil
}
