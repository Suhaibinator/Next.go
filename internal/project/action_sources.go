const generatedActionsHeader = "// Code generated by nextgo actions. DO NOT EDIT.\n"

var actionOutputNames = []string{"nextgo_gen.go", "nextgo_gen_js.go", "nextgo_gen_server.go"}

func actionFiles(root string) []string {
	paths := make([]string, len(actionOutputNames))
	for i, name := range actionOutputNames {
		paths[i] = filepath.Join(root, "actionrefs", name)
	}
	return paths
}

// ActionSources emits shared references plus separate native and browser
// adapters. Every adapter delegates to mutation.Contract; no transport is added.
func ActionSources(p *Project) (map[string][]byte, error) {
	if err := validateActions(p.Actions); err != nil {
		return nil, err
	}
	actions := append([]Action(nil), p.Actions...)
	sort.Slice(actions, func(i, j int) bool { return actions[i].Name < actions[j].Name })
	const anchor = "actionGeneration_GENERATED_SET_ANCHOR"
	var shared, browser, native strings.Builder
	shared.WriteString(generatedActionsHeader + "\n// Package actionrefs provides generated typed application action references.\npackage actionrefs\n")
	browser.WriteString(generatedActionsHeader + "//go:build js && wasm\n\npackage actionrefs\n")
	native.WriteString(generatedActionsHeader + "//go:build !js\n\npackage actionrefs\n")
	if len(actions) > 0 {
		shared.WriteString("import(\n")
		browser.WriteString("import(\"context\"\n")
		fmt.Fprintf(&browser, "mutation %q\nclient %q\n", framework+"/mutation", framework+"/client")
		for i, a := range actions {
			fmt.Fprintf(&shared, "a%d %q\n", i, a.Import)
			fmt.Fprintf(&browser, "a%d %q\n", i, a.Import)
		}
		shared.WriteString(")\n")
		browser.WriteString(")\n")
	}
	fmt.Fprintf(&native, "import(actions %q\n", framework+"/actions")
	if len(actions) > 0 {
		native.WriteString("\"fmt\"\n")
	}
	for i, a := range actions {
		fmt.Fprintf(&native, "a%d %q\n", i, a.Import)
	}
	native.WriteString(")\n")
	fmt.Fprintf(&shared, "// Target adapters reference this generation-specific anchor. Mixed files fail compilation.\ntype %s struct{}\n", anchor)
	fmt.Fprintf(&browser, "var _ %s\n", anchor)
	fmt.Fprintf(&native, "var _ %s\n", anchor)
	for i, a := range actions {
		fmt.Fprintf(&shared, "\ntype %sInput = a%d.Input\ntype %sOutput = a%d.Output\n// %sPath returns an application-relative path; apply nextgo.URL for HTML forms.\nfunc %sPath()string{return a%d.Contract.Path()}\n", a.Symbol, i, a.Symbol, i, a.Symbol, a.Symbol, i)
		fmt.Fprintf(&browser, "\n// %s calls the existing typed contract without automatic navigation or retry.\nfunc %s(ctx context.Context,input %sInput,options ...mutation.CallOptions)(mutation.Response[%sOutput],error){return a%d.Contract.Call(ctx,input,options...)}\n", a.Symbol, a.Symbol, a.Symbol, a.Symbol, i)
		fmt.Fprintf(&browser, "\n// %sMultipart delegates multipart transport to the existing typed contract.\nfunc %sMultipart(ctx context.Context,form *client.Multipart,options ...mutation.CallOptions)(mutation.Response[%sOutput],error){return a%d.Contract.CallMultipart(ctx,form,options...)}\n", a.Symbol, a.Symbol, a.Symbol, i)
		fmt.Fprintf(&browser, "\n// %sAndRefresh preserves typed confirmation independently of its fresh view.\nfunc %sAndRefresh(ctx context.Context,input %sInput,options ...mutation.CallOptions)(mutation.RefreshResponse[%sOutput],error){return a%d.Contract.CallAndRefresh(ctx,input,options...)}\n", a.Symbol, a.Symbol, a.Symbol, a.Symbol, i)
		fmt.Fprintf(&browser, "\n// %sMultipartAndRefresh delegates the combined multipart action and fresh view.\nfunc %sMultipartAndRefresh(ctx context.Context,form *client.Multipart,options ...mutation.CallOptions)(mutation.RefreshResponse[%sOutput],error){return a%d.Contract.CallMultipartAndRefresh(ctx,form,options...)}\n", a.Symbol, a.Symbol, a.Symbol, i)
	}
	native.WriteString("\n// Register binds generated contracts to the supplied app-owned router.\nfunc Register(router *actions.Router){\n")
	// Validate the whole descriptor set before binding any entry. Router duplicate
	// checking remains authoritative for collisions with manual registrations.
	for i, a := range actions {
		fmt.Fprintf(&native, "if a%d.Contract.Name()!=%q||a%d.Contract.Revision()!=%q{panic(fmt.Errorf(\"generated action contract changed: %%s; regenerate actionrefs\",%q))}\n", i, a.Name, i, a.Revision, a.Name)
	}
	for i := range actions {
		fmt.Fprintf(&native, "a%d.Contract.Bind(router,a%d.Handle,a%d.Options())\n", i, i, i)
	}
	native.WriteString("}\n")
	sources := map[string]string{"nextgo_gen.go": shared.String(), "nextgo_gen_js.go": browser.String(), "nextgo_gen_server.go": native.String()}
	result := map[string][]byte{}
	hash := sha256.New()
	for _, name := range actionOutputNames {
		source := sources[name]
		data, err := format.Source([]byte(source))
		if err != nil {
			return nil, fmt.Errorf("generate action reference %s: %w", name, err)
		}
		result[name] = data
		fmt.Fprintf(hash, "%s\x00%d\x00", name, len(data))
		_, _ = hash.Write(data)
	}
	// Hash every generated target, including generator template changes. A
	// declaration-only hash would miss mixed outputs from generator upgrades.
	finalAnchor := fmt.Sprintf("actionGeneration_%x", hash.Sum(nil))
	for name, data := range result {
		text := string(data)
		text = strings.ReplaceAll(text, "type "+anchor+" struct{}", "type "+finalAnchor+" struct{}")
		text = strings.ReplaceAll(text, "var _ "+anchor+"\n", "var _ "+finalAnchor+"\n")
		result[name] = []byte(text)
	}
	return result, nil
}

// GenerateActions preflights every owned output, then replaces changed files
// atomically one at a time. It is not a batch-atomic transaction. Generation
// anchors fail closed if a build observes mixed old/new target files. Re-run
// generation to repair an interrupted publication. Check mode never writes.
func GenerateActions(p *Project, check bool) ([]string, error) {
	sources, err := ActionSources(p)
	if err != nil {
		return nil, err
	}
	paths := actionFiles(p.Root)
	dir := filepath.Join(p.Root, "actionrefs")
	if err := validateActionOutputs(dir, p.Actions); err != nil {
		return nil, err
	}
	changed := map[string][]byte{}
	for _, path := range paths {
		data := sources[filepath.Base(path)]
		info, err := os.Lstat(path)
		if err == nil {
			if !info.Mode().IsRegular() {
				return nil, fmt.Errorf("action reference output must be a regular file: %s", path)
			}
			existing, err := os.ReadFile(path)
			if err != nil {
				return nil, err
			}
			if !bytes.HasPrefix(existing, []byte(generatedActionsHeader)) {
				return nil, fmt.Errorf("refusing to overwrite unowned action reference file: %s", path)
			}
			if bytes.Equal(existing, data) {
				continue
			}
		} else if !os.IsNotExist(err) {
			return nil, err
		}
		changed[path] = data
	}
	if check && len(changed) > 0 {
		return nil, fmt.Errorf("action references missing or stale; run nextgo generate %s", p.Root)
	}
	if check || len(changed) == 0 {
		return paths, nil
	}
	if err := os.MkdirAll(dir, 0755); err != nil {
		return nil, err
	}
	for _, path := range paths {
		if data, ok := changed[path]; ok {
			if err := writeActionOutput(path, data); err != nil {
				return nil, err
			}
		}
	}
	return paths, nil
}

func validateActionOutputs(dir string, actions []Action) error {
	info, err := os.Lstat(dir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("actionrefs must be a real directory: %s", dir)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	owned := map[string]bool{}
	for _, name := range actionOutputNames {
		owned[name] = true
	}
	symbols := map[string]bool{"Register": true}
	for _, a := range actions {
		for _, symbol := range actionSymbols(a) {
			symbols[symbol] = true
		}
	}
	for _, entry := range entries {
		if entry.Name() == "go.mod" {
			return fmt.Errorf("actionrefs cannot use a nested module: %s", dir)
		}
		if owned[entry.Name()] || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		info, err := os.Lstat(path)
		if err != nil {
			return err
		}
		if !info.Mode().IsRegular() {
			return fmt.Errorf("actionrefs source must be a regular file: %s", path)
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(data, []byte(generatedActionsHeader)) {
			return fmt.Errorf("unrecognized stale generated action output: %s", path)
		}
		file, err := parser.ParseFile(token.NewFileSet(), path, data, 0)
		if err != nil {
			return err
		}
		if file.Name.Name != "actionrefs" && !(strings.HasSuffix(entry.Name(), "_test.go") && file.Name.Name == "actionrefs_test") {
			return fmt.Errorf("actionrefs source has incompatible package %s: %s", file.Name.Name, path)
		}
		if file.Name.Name == "actionrefs_test" {
			continue
		}
		for _, decl := range file.Decls {
			var names []string
			switch value := decl.(type) {
			case *ast.FuncDecl:
				if value.Recv == nil {
					names = append(names, value.Name.Name)
				}
			case *ast.GenDecl:
				for _, raw := range value.Specs {
					switch spec := raw.(type) {
					case *ast.TypeSpec:
						names = append(names, spec.Name.Name)
					case *ast.ValueSpec:
						for _, id := range spec.Names {
							names = append(names, id.Name)
						}
					}
				}
			}
			for _, name := range names {
				if symbols[name] {
					return fmt.Errorf("actionrefs symbol %s collides with generated declaration: %s", name, path)
				}
			}
		}
	}
	return nil
}

func writeActionOutput(path string, data []byte) error {
	temp, err := os.CreateTemp(filepath.Dir(path), ".nextgo-actions-*")
	if err != nil {
		return err
	}
	defer os.Remove(temp.Name())
	defer temp.Close()
	if _, err = temp.Write(data); err != nil {
		return err
	}
	if err = temp.Chmod(0644); err != nil {
		return err
	}
	if err = temp.Close(); err != nil {
		return err
	}
	return os.Rename(temp.Name(), path)
}
